#include <iostream>

int main() {
    std::cout << "7 + 4 =" << 7 + 4 << std::endl;  // addition;
    std::cout << "7 - 4 =" << 7 - 4 << std::endl;    // subtraction;
    std::cout << "7 * 4 =" << 7 * 4 << std::endl;  // multiplication;
    std::cout << "8 / 4 =" << 8 / 4 << std::endl;  // division;
    std::cout << "7.0 / 2 =" << (float)7 / 2 << std::endl;  // decimal;
}